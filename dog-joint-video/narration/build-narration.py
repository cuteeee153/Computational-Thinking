RATE = 4.3  # 每秒字數（中文 AI 配音一般語速，約 4～4.5 字／秒）
def est(t):
    chars = len(re.sub(r'[，。、：；？！「」\s]', '', t.replace('COAST', 'XX')))
    pauses = len(re.findall(r'[，、；：]', t)) * .25 + len(re.findall(r'[。？！]', t)) * .45
    return chars, chars / RATE + pauses
rows = []; total = 0
for s in sc:
    t = N[s['id']]; dur = s['end'] - s['start']
    c, e = est(t) if t else (0, 0); total += e
    diff = e - dur
    st = '—' if not t else ('OK' if diff <= 0 else ('略超出' if diff <= 1 else '超出'))
    rows.append((s, t, c, e, dur, diff, st))

